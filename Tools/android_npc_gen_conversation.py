def rules_yaml() -> str:
    out = [HEADER, "\n- type: androidIntentRules\n  id: Default\n  defaultLanguage: en\n  fallbackIntent: unrelated\n"]
    out.append("  languages:\n")
    for lang in LANGS:
        out.append(f"  - id: {lang}\n    hints:\n{qlist(LANG_HINTS[lang], 4)}")
        a = ALERTS[lang]
        for key in ("threat", "emergency", "noLocation", "noSupply"):
            out.append(f"    {key}: {q(a[key])}\n")
    out.append("  phrases:\n")
    for lang in LANGS:
        for intent, phrases in lc.INTENT_PHRASES[lang].items():
            out.append(f"  - lang: {lang}\n    intent: {intent}\n    phrases:\n{qlist(sorted(phrases), 4)}")
    out.append("  keywords:\n")
    for lang in LANGS:
        for intent, patterns in lc.INTENT_KEYWORDS[lang]:
            out.append(f"  - lang: {lang}\n    intent: {intent}\n    patterns:\n{qlist(patterns, 4)}")
    out.append("  tone:\n")
    for lang in LANGS:
        for level in (2, 1):
            out.append(f"  - lang: {lang}\n    level: {level}\n    patterns:\n{qlist(TONE[lang][level], 4)}")
    out.append("  locations:\n")
    for target, aliases in LOCATION_ALIASES.items():
        out.append(f"  - target: {target}\n    aliases:\n{qlist(aliases, 4)}")
    return "".join(out)


def job_yaml(job: str, spec: dict) -> str:
    path = SRC / "jobs" / f"{spec['file']}.json"
    data = json.loads((path if path.exists() else LOCAL_JOBS / f"{spec['file']}.json").read_text(encoding="utf-8"))
    out = [f"\n- type: androidConversation\n  id: {job}\n  job: {job}\n"]
    out.append("  backendState:\n")
    for key, value in data["hidden_state"].items():
        out.append(f"    {key}: {q(value)}\n")
    out.append("  backendQuestions:\n")
    for lang in LANGS:
        qs = data.get("questions_fr") if lang == "fr" else None
        qs = qs or data["questions"]
        intent, tone = qs["intent"], qs["tone"]
        out.append(f"  - lang: {lang}\n    intentInstructions: {q(intent['instructions'])}\n    intentCriteria:\n")
        for key, desc in intent["criteria"].items():
            out.append(f"      {key}: {q(desc)}\n")
        out.append(f"    toneInstructions: {q(tone['instructions'])}\n    toneCriteria:\n{qlist(tone['criteria'], 4)}")
    if spec["effects"]:
        out.append("  effects:\n")
        for intent, effect in spec["effects"].items():
            out.append(f"    {intent}: {effect}\n")
    if spec["supplies"]:
        out.append("  supplies:\n")
        for patterns, items in spec["supplies"]:
            out.append(f"  - patterns:\n{qlist(patterns, 4)}    items:\n{qlist(items, 4)}")
    out.append("  responses:\n")
    for lang in LANGS:
        for intent, levels in data["responses"][lang].items():
            assert len(levels) == 3, (job, lang, intent)
            out.append(f"  - lang: {lang}\n    intent: {intent}\n")
            for name, variants in zip(("calm", "direct", "threatening"), levels):
                out.append(f"    {name}:\n{qlist(variants, 4)}")
    return "".join(out)


